function contained(root: string, path: string): boolean {
  const rel = relative(root, path);
  return rel !== '' && rel !== '..' && !rel.startsWith('..' + sep) && !isAbsolute(rel);
}

/** Reuse the exact Pi discovery/catalog policy from Strategy Forge's session loader. */
export async function loadGameplayContext(root = projectRoot) {
  const skillDirectory = resolve(root, 'skills');
  const skillRoot = realpathSync(skillDirectory);
  const discovered = loadSkills({ cwd: root, agentDir: resolve(root, '.pi'), skillPaths: [skillDirectory], includeDefaults: false });
  discovered.skills = discovered.skills.filter(skill => {
    if (contained(skillRoot, realpathSync(skill.filePath))) return true;
    discovered.diagnostics.push({ type: 'warning', path: skill.filePath, message: 'Skill resolves outside the gameplay skill directory.' });
    return false;
  });
  const allowedRoots = [...new Set(discovered.skills.map(skill => realpathSync(skill.baseDir)))];
  const basePrompt = await loadSystemPrompt(root);
  const catalog = formatSkillsForPrompt(discovered.skills, 'indirect');
  const fullContext = [basePrompt, catalog, bindings].filter(Boolean).join('\n\n');
  const instructions = bootstrapInstructions;

  async function readSkillResource(uri: URL): Promise<string> {
    if (uri.protocol !== 'file:' || uri.host || uri.search || uri.hash) throw new Error('Use a local file:// URI from the gameplay skill catalog.');
    const path = fileURLToPath(uri);
    if (/(?:^|[\\/])\./.test(path)) throw new Error('Hidden paths and traversal are outside the skill resource scope.');
    const target = await realpath(path);
    if (!contained(skillRoot, target) || !allowedRoots.some(base => contained(base, target))) throw new Error('Resource is outside the discovered gameplay skill directories.');
    if (!(await stat(target)).isFile()) throw new Error('A skill resource must be a regular file.');
    return readFile(target, 'utf8');
  }

  async function expandSkill(name: string, instructions = ''): Promise<string> {
    const skill = discovered.skills.find(skill => skill.name === name);
    if (!skill) throw new Error('Unknown gameplay skill: ' + name);
    const body = stripFrontmatter(await readSkillResource(pathToFileURL(skill.filePath))).trim();
    // Match Pi AgentSession._expandSkillCommand, including frontmatter removal,
    // reference-directory annotation, whitespace and appended user instructions.
    const block = `<skill name="${skill.name}" location="${skill.filePath}">\nReferences are relative to ${skill.baseDir}.\n\n${body}\n</skill>`;
    return instructions.trim() ? `${block}\n\n${instructions.trim()}` : block;
  }
  return { root, basePrompt, catalog, instructions, fullContext, skills: discovered.skills, diagnostics: discovered.diagnostics, readSkillResource, expandSkill };
}

export function registerGameplayResources(server: McpServer, context: Awaited<ReturnType<typeof loadGameplayContext>>): void {
  for (const [name, uri, title, description, text] of [
    ['agent-context', 'balatro://context', 'Full agent context', 'balatro://rules, balatro://protocol, the gameplay skill catalog and notes on reading skills through MCP, in one document. Read it instead of those resources, not in addition; it is long.', context.fullContext],
    ['skill-index', 'balatro://skills', 'Skill index', 'JSON list of gameplay skills: name, description, file:// URI for resources/read, whether the model may invoke it, and discovery warnings.', JSON.stringify({ catalog: context.catalog, skills: context.skills.map(skill => ({ ...skill, uri: pathToFileURL(skill.filePath).href })), diagnostics: context.diagnostics }, null, 2)],
  ]) {
    const mimeType = name === 'skill-index' ? 'application/json' : 'text/markdown';
    server.registerResource(name, uri, { title, description, mimeType }, async url => ({ contents: [{ uri: url.href, mimeType, text }] }));
  }
  for (const [name, uri, title, description, path] of [
    ['game-rules', 'balatro://rules', 'Balatro game rules', 'Mechanics of Balatro 1.0.1o: run lifecycle, poker hands, scoring order and retriggers, card modifiers, decks and stakes, Boss Blinds, economy and shop, and every consumable, pack, Tag, Voucher, Joker and Challenge. Long; read it when a mechanic is unclear.', 'model/context/balatro.md'],
    ['decision-protocol', 'balatro://protocol', 'Decision protocol', 'One page on conduct during play: when to act and when to stop, starting or continuing a run, recovery after errors, and what to check before playing or buying.', 'skills/core.md'],
  ]) {
    server.registerResource(name, uri, { title, description, mimeType: 'text/markdown' }, async url => ({ contents: [{ uri: url.href, mimeType: 'text/markdown', text: await readFile(resolve(context.root, path), 'utf8') }] }));
  }
  // List only automatically invocable skill bodies. Explicit-only skills remain
  // available via their named prompts, matching Pi's catalog visibility policy.
  server.registerResource('skill-files', new ResourceTemplate('file:///{+path}', {
    list: async () => ({ resources: context.skills.filter(skill => !skill.disableModelInvocation).map(skill => ({ name: skill.name, description: skill.description, uri: pathToFileURL(skill.filePath).href, mimeType: 'text/markdown' })) }),
  }), { title: 'Gameplay skill files', description: 'SKILL.md files of gameplay skills and the files they reference, by file:// URI. Only files inside the discovered skill directories can be read.' }, async uri => ({
    contents: [{ uri: uri.href, mimeType: extname(fileURLToPath(uri)) === '.json' ? 'application/json' : 'text/plain', text: await context.readSkillResource(uri) }],
  }));
  for (const skill of context.skills) {
    server.registerPrompt('skill:' + skill.name, {
      title: skill.name, description: skill.description,
      argsSchema: z.object({ instructions: z.string().optional().describe('Optional user instructions appended after the skill body, as in Pi /skill:name.') }).strict(),
    }, async ({ instructions }) => ({ messages: [{ role: 'user', content: { type: 'text', text: await context.expandSkill(skill.name, instructions) } }] }));
  }
}
